#!/usr/bin/env python3
"""Export an NQX-S1 build as a Tiny Tapeout project directory.

    python tools/export_tinytapeout.py [--dim 32] [--out tinytapeout]

Produces a directory that drops into a repository created from Tiny
Tapeout's template (ttgf-verilog-template / ttihp-verilog-template):
info.yaml, src/ (wrapper + one flattened RTL file with the generated
parameters inlined), docs/info.md and a cocotb test that checks the design
bit-exactly against the model at the chosen DIM.

Pin map (24 TT I/Os):
    ui_in[7:0]   in_bus        uo_out[7:0]  out_bus
    uio[0] in    in_req        uio[1] out   in_ack
    uio[2] out   out_req       uio[3] in    out_ack
    uio[4] out   busy          uio[7:5]     unused (inputs)
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "model"))

from gen_params import atan_vh, params_vh  # noqa: E402

from nqx_s1.params import S1Params  # noqa: E402

TOP = "tt_um_hermandoronin_nqx_s1"
RTL_ORDER = [
    "nqx_s1_top.sv", "nqx_s1_hsio.sv", "nqx_s1_core.sv", "nqx_s1_cordic.sv",
    "nqx_s1_cordic_iter.sv", "nqx_s1_rcode.sv", "nqx_s1_rsign.sv", "nqx_s1_tcode.sv",
    "nqx_s1_qdec.sv", "nqx_s1_div28.sv", "nqx_s1_rf.sv",
]


def flatten_rtl(p: S1Params) -> str:
    params = params_vh(p).replace("// GENERATED", "// Inlined, GENERATED")
    atan = "\n".join(atan_vh(p).splitlines()[2:])
    out = [
        f"// NQX-S1, DIM={p.dim}: flattened by tools/export_tinytapeout.py from nqx-silicon/rtl.",
        "// Do not edit; regenerate instead.",
        "/* verilator lint_off DECLFILENAME */",
        params,
    ]
    for name in RTL_ORDER:
        text = (ROOT / "rtl" / name).read_text()
        text = text.replace('`include "nqx_s1_params.vh"\n', "")
        text = re.sub(r'^\s*`include "nqx_s1_atan.vh"\s*$', atan, text, flags=re.M)
        out.append(f"// ---- {name} " + "-" * max(0, 60 - len(name)) + "\n" + text)
    return "\n".join(out)


WRAPPER = """/*
 * NQX-S1 (NautilusQuant golden-angle KV compression engine) for Tiny Tapeout.
 * SPDX-License-Identifier: Apache-2.0
 */
`default_nettype none

module {top} (
    input  wire [7:0] ui_in,
    output wire [7:0] uo_out,
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);
    wire in_ack, out_req, busy;

    assign uio_oe  = 8'b0001_0110;
    assign uio_out = {{3'b000, busy, 1'b0, out_req, in_ack, 1'b0}};

    nqx_s1_top #(.ITER_CORDIC(1)) u_nqx (
        .clk     (clk),
        .rst_n   (rst_n),
        .in_bus  (ui_in),
        .in_req  (uio_in[0]),
        .in_ack  (in_ack),
        .out_bus (uo_out),
        .out_req (out_req),
        .out_ack (uio_in[3]),
        .busy    (busy)
    );

    wire _unused = &{{ena, uio_in[7:4], uio_in[2:1], 1'b0}};
endmodule

`default_nettype wire
"""

