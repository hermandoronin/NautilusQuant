DOCS = """## How it works

NQX-S1 compresses a {dim}-element vector of signed 16-bit integers (an LLM
KV-cache head slice) into {pkt} bytes and restores it. The pipeline is
NautilusQuant: Givens rotations whose angles follow the golden angle,
generated by a 32-bit phase accumulator (increments 0x61C88647 and
0x9E3779B9) and applied by a CORDIC with shifts and adds only. Then comes a
polar transform, a 3-bit radius and 3-bit circular angle code per pair, and
one residual bit per value. The design is bit-exact with the Python model in
nqx-silicon/model and uses the area-saving iterative CORDIC.

Full specification: https://github.com/hermandoronin/NautilusQuant/tree/main/nqx-silicon/spec

## How to test

The host writes command bytes on ui_in with a 4-phase handshake
(uio[0] in_req / uio[1] in_ack) and reads results on uo_out
(uio[2] out_req / uio[3] out_ack):

1. Set ui_in, raise in_req, wait for in_ack, drop in_req, wait for in_ack low.
2. When out_req is high, read uo_out, raise out_ack, wait for out_req low,
   drop out_ack.

Send `72 00` (read CSR 0): the chip answers `31 58 51 4E` ("NQX1").
Send `60` followed by {inb} bytes (a vector) to receive a {pkt}-byte packet.
Send `61` followed by the packet to get the vector back.

## External hardware

None. The demo board's microcontroller drives the handshake.
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dim", type=int, default=32)
    ap.add_argument("--tiles", default="4x4")
    ap.add_argument("--out", type=Path, default=ROOT / "tinytapeout")
    args = ap.parse_args()
    p = S1Params(dim=args.dim)

    out = args.out
    if out.exists():
        shutil.rmtree(out)
    (out / "src").mkdir(parents=True)
    (out / "docs").mkdir()
    (out / "test").mkdir()

    (out / "src" / f"nqx_s1_dim{p.dim}.v").write_text(flatten_rtl(p))
    (out / "src" / f"{TOP}.v").write_text(WRAPPER.format(top=TOP))
    (out / "info.yaml").write_text(INFO.format(dim=p.dim, tiles=args.tiles, top=TOP))
    (out / "docs" / "info.md").write_text(
        DOCS.format(dim=p.dim, pkt=p.packet_bytes, inb=2 * p.dim)
    )
    shutil.copytree(ROOT / "model" / "nqx_s1", out / "test" / "nqx_s1",
                    ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy(ROOT / "tools" / "tt_test" / "README.md", out / "README.md")
    shutil.copy(ROOT / "tools" / "tt_test" / "gitignore", out / ".gitignore")
    shutil.copy(ROOT / "tools" / "tt_test" / "config.json", out / "src" / "config.json")
    shutil.copy(ROOT / "tools" / "tt_test" / "requirements.txt", out / "test" / "requirements.txt")
    for f in ("tb.v", "test.py", "Makefile"):
        text = (ROOT / "tools" / "tt_test" / f).read_text()
        text = text.replace("@TOP@", TOP).replace("@DIM@", str(p.dim))
        (out / "test" / f).write_text(text)
    print(f"exported Tiny Tapeout project to {out} (DIM={p.dim}, tiles={args.tiles})")


if __name__ == "__main__":
    main()
